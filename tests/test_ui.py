def ok(cond, msg):
    global falhas
    print(("  OK  " if cond else "  FALHA ") + msg)
    falhas += 0 if cond else 1


def checar(msg, fn):
    """Roda uma asserção do Playwright e registra OK/FALHA sem interromper o resto."""
    try:
        fn()
        ok(True, msg)
    except AssertionError as e:
        ok(False, f"{msg} -> {str(e).splitlines()[0][:160]}")


